import {z} from 'zod';

// Контракт входа композиции `Motion` — сплит: инфографика и говорящая
// голова в одном кадре. Граница та же, что у `Reel`: питон собирает
// ровно этот JSON, Remotion только рисует.
//
// Чем `Motion` отличается от `Reel`. В `Reel` дубль занимает весь холст,
// а слова лежат поверх него. Здесь холст поделён швом: одна половина —
// дубль, вторая — панель, которая меняется по ходу речи. Панель не
// иллюстрация к ролику, а вторая дорожка: пока человек говорит «просто
// опиши», на панели набирается та самая строка.
//
// Вся арифметика сделана до этого файла: куски отобраны, слова разложены
// по страницам, блоки панели расставлены по секундам. Секунды блоков —
// это секунды **готового** ролика, уже после выброшенных пауз и после
// первого кадра, ровно как у `pages`.

const segment = z.object({
  from: z.number(),   // секунда в исходном дубле
  to: z.number(),
});

const focus = z.object({
  t: z.number(),      // секунда в готовом ролике, уже после нарезки
  x: z.number(),      // 0..1 по ширине исходного кадра
  y: z.number(),
});

const word = z.object({
  text: z.string(),
  start: z.number(),
  end: z.number(),
});

const page = z.object({
  start: z.number(),
  end: z.number(),
  words: z.array(word),
});

// Один экран панели. Живёт от `start` до `end`, дальше его сменяет
// следующий. Дырка между блоками — это пустая панель, а не ошибка:
// на вдохе показывать нечего.
const block = z.object({
  start: z.number(),
  end: z.number(),

  // Надзаголовок капсом с разрядкой: «БЕЗ КОДА», «ТРЕТИЙ». Держит
  // место в списке и даёт панели заголовок, когда картинка сама по
  // себе ничего не объясняет.
  kicker: z.string().optional(),

  // Имя файла внутри public/. Remotion в этой версии не отдаёт файлы
  // вне public/ ни голым путём, ни через file://, поэтому питон копирует
  // скрин туда и передаёт сюда только имя.
  imagePath: z.string().optional(),

  // Чем заполнена карточка, когда картинки нет: строки текста. Первая
  // строка крупная, остальные мельче — так набирается «Google Opal /
  // Google Opal» из примера.
  lines: z.array(z.string()).default([]),

  // Список, который набирается под речь: пункт выезжает в ту секунду,
  // когда человек его называет, а не вместе со всей карточкой.
  // Список, показанный стеной, читается быстрее речи — зритель дочитал
  // и ушёл раньше, чем автор дошёл до второго пункта.
  //
  // `at` — секунда готового ролика. Считает питон по словам: пункт
  // привязывается к слову, с которого он начинается в расшифровке.
  items: z.array(z.object({text: z.string(), at: z.number()})).default([]),

  // Панель на весь кадр: дубль на это время уходит целиком. Так сделан
  // разгон в начале ролика, где голова ещё не нужна.
  full: z.boolean().default(false),

  // Чем блок занят.
  //
  // `card` — карточка со скрином или строками, как было. Остальные три
  // двигаются сами, а не только выезжают: картинка анимировать себя не
  // умеет, нарисованное умеет.
  //
  // `icon`   — иконка продукта и его имя под ней, как в референсе;
  // `counter`— число набирается от нуля в ту секунду, когда оно звучит;
  // `scale`  — шкала со ступенями, бегунок едет по ним под речь.
  //
  // `media` — материал из альбома к дублю: запись экрана или картинка,
  //            снятые автором. Файл в `videoPath` или `imagePath`.
  // `art`    — картинка по теме от Nano Banana, когда записи нет. Сама
  //            не двигается, поэтому двигает её шаблон.
  kind: z
    .enum(['card', 'icon', 'counter', 'scale', 'media', 'art'])
    .default('card'),

  // `media`: запись из альбома — имя в public/ и её длина. Длиннее блока
  // — ускоряется до двух раз и обрезается, короче — встаёт последним
  // кадром, а не гаснет.
  videoPath: z.string().optional(),
  videoSeconds: z.number().optional(),
  // Мерки кадра материала: вписать его, не растягивая.
  mediaWidth: z.number().optional(),
  mediaHeight: z.number().optional(),

  // `counter`: до какого числа считать и в какую секунду готового
  // ролика число набирается. Секунду даёт слово в расшифровке.
  value: z.number().optional(),
  valueAt: z.number().optional(),
});

export const motionPropsSchema = z.object({
  videoPath: z.string(),
  videoWidth: z.number(),
  videoHeight: z.number(),

  // Что осталось от дубля после выброшенных пауз.
  segments: z.array(segment).min(1),

  // Куда едет кадр внутри своей половины. Пусто — стоим по центру.
  pan: z.array(focus).default([]),

  // Где голова. В разобранном примере она снизу, панель сверху —
  // отсюда дефолт. Наверх её ставит одна строка в питоне, а не вторая
  // композиция: кроме порядка половин не меняется ничего.
  headAnchor: z.enum(['top', 'bottom']).default('bottom'),

  // Доля высоты холста, которую занимает панель. 0.448 — замер с кадра
  // примера: 860 пикселей из 1920.
  split: z.number().default(0.448),

  // Дефолты — токены бренда (`design/tokens.css`): графит, неон,
  // молоко. Питон всё равно передаёт их явно из файла бренда, но
  // дефолт, снятый с чужого аккаунта, однажды доедет до рендера.
  panelColor: z.string().default('#1F1F1F'),
  glowColor: z.string().default('rgba(198, 222, 72, 0.13)'),
  cardColor: z.string().default('rgba(248, 245, 241, 0.06)'),
  accentColor: z.string().default('#C6DE48'),
  textColor: z.string().default('#F8F5F1'),

  blocks: z.array(block).default([]),

  // Караоке. Строка садится на шов и идёт плашкой, а не градиентом:
  // градиент на шве пачкает низ панели.
  pages: z.array(page).default([]),

  cta: z.string().optional(),
  brandName: z.string().optional(),

  width: z.number().default(1080),
  height: z.number().default(1920),
  fps: z.number().default(30),
  outroSeconds: z.number().default(1.8),
});

export type MotionProps = z.infer<typeof motionPropsSchema>;
export type MotionBlock = z.infer<typeof block>;
