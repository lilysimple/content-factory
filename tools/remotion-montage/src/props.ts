import {z} from 'zod';

// Контракт входа: orchestrator/montage.py собирает ровно этот JSON и
// передаёт через --props. Питон не знает про Remotion, а Remotion не
// знает про базу — граница ровно здесь, одна точка правды на форму входа.
//
// Вся арифметика сделана до этого файла: паузы найдены, куски отобраны,
// центр движения посчитан, слова разложены по страницам. Remotion только
// рисует. Так проверять поведение можно питоном на стенде, не поднимая
// браузер ради каждой проверки.

const segment = z.object({
  from: z.number(),   // секунда в исходном дубле
  to: z.number(),
});

const focus = z.object({
  t: z.number(),      // секунда в готовом ролике, уже после нарезки
  x: z.number(),      // 0..1 по ширине исходного кадра
  y: z.number(),
});

const word = z.object({
  text: z.string(),
  start: z.number(),  // секунда в готовом ролике
  end: z.number(),
});

// Строка обложки: текст, цвет и кегль уже посчитаны питоном по ТЗ бренда.
const coverLine = z.object({
  text: z.string(),
  color: z.string(),
  size: z.number(),
});

// Музыкальная подложка. Нет поля — нет и музыки, и это не забывчивость:
// банк треков человек наполняет руками (`design/music/` в папке бренда),
// и положить туда файл — это и есть согласие. Пустой банк значит «не
// надо», а не «ещё не дошли руки».
//
// Уровни считает питон, а не шаблон: пропорция между голосом и музыкой
// это решение, и держать его в двух местах — верный способ развести их
// молча при первой же правке.
export const musicProps = z.object({
  src: z.string(),                       // имя файла внутри public/
  bed: z.number().default(0.14),         // под речью
  open: z.number().default(0.42),        // на обложке и в финале
});

export type MusicProps = z.infer<typeof musicProps>;

const page = z.object({
  start: z.number(),
  end: z.number(),
  words: z.array(word),
});

// Накладка: присланное человеком фото поверх полного кадра, сверху.
// Отличается от блока панели тем, что холст не делится: дубль идёт во
// весь кадр, а фото выезжает на своей фразе и уходит. Время — секунды
// тела ролика, как у страниц караоке: обложку шаблон прибавляет сам.
const insert = z.object({
  src: z.string(),    // имя файла внутри public/
  start: z.number(),
  end: z.number(),
  // Доля ширины холста. Считает питон по меркам самой картинки: он
  // знает, что вертикальный кадр, вписанный по ширине, закроет лицо.
  width: z.number().default(0.66),
});

// ── слои поверх дубля ────────────────────────────────────────────────
//
// Второй формат монтажа, рядом со сплитом. Кадр не делится вовсе: дубль
// идёт во весь экран от первой секунды до последней, склеек нет, и вся
// работа идёт слоями поверх — заголовок, снимок страницы, плашка
// площадки. Панель и слои взаимно исключены: в сплите половина кадра
// занята, и класть туда заголовок во всю ширину некуда.
//
// Время — секунды тела ролика, как у накладок и страниц караоке:
// обложку шаблон прибавляет сам.

// Место на снимке, которое подсвечивает маркер. Доли снимка от его
// левого верхнего угла, а не пиксели: один и тот же снимок едет и в
// карточке, и во весь кадр, и пиксели там разные.
const proofMark = z.object({
  x: z.number(),
  y: z.number(),
  w: z.number(),
  h: z.number(),
  at: z.number(),     // секунда тела ролика, на которой маркер доползает
});

const layer = z.object({
  kind: z.enum(['title', 'proof', 'chrome']),
  start: z.number(),
  end: z.number(),

  // `title` — строки заголовка капсом и рукописный акцент поверх них.
  // `chrome` — первая строка это имя карточки, вторая подпись под ним.
  lines: z.array(z.string()).default([]),
  script: z.string().default(''),
  // Стрелка-завиток от рукописного акцента. `none` — её нет: стрелка,
  // которая никуда не показывает, читается помаркой.
  arrow: z.enum(['none', 'down', 'left', 'right']).default('none'),

  // `proof` — имя снимка внутри public/ и его натуральный размер:
  // без размера не посчитать, на сколько прокрутить снимок до метки.
  src: z.string().default(''),
  imageWidth: z.number().default(0),
  imageHeight: z.number().default(0),
  marks: z.array(proofMark).default([]),
  // Секунда тела, на которой снимок разворачивается во весь кадр.
  // Нет поля — он так и остаётся карточкой в углу.
  openAt: z.number().optional(),
});

export const reelPropsSchema = z.object({
  // Имя файла внутри public/ (не абсолютный путь): Remotion в этой версии
  // не отдаёт произвольные файлы вне public/ ни голым путём, ни через
  // file://, поэтому montage.py копирует видео и обложку в public/ перед
  // рендером и передаёт сюда только имя файла.
  videoPath: z.string(),
  // Первый кадр: либо обложка Дизайнера под этот холст, либо снятый из
  // самого дубля кадр. Кто из двух — решает питон, здесь просто картинка.
  coverPath: z.string().optional(),
  // Обложка, собранная движением: имя mp4 внутри public/. Клип
  // наезжает на утверждённый человеком кадр и идёт вместо неподвижной
  // обложки целиком — со своим затемнением и своими словами, если они
  // на картинке есть. Нет поля — первый кадр рисуется, как рисовался.
  coverClipPath: z.string().optional(),
  // Кадр из дубля уводится в размытый фон, обложка Дизайнера — нет.
  // Свёрстанная обложка это готовая картинка со своей композицией, а
  // кадр записи экрана — это чужой текст под нашим заголовком.
  coverBlur: z.boolean().default(false),
  // Куда ведём кроп первого кадра: то же, что object-position в CSS.
  // Кадр 16:9 на холсте 9:16 теряет по бокам две трети ширины, и при
  // кропе по центру человек, сидящий сбоку, уезжает за край. Точку
  // считает питон по рамке лица — здесь только подставляем.
  coverFocus: z.object({x: z.number(), y: z.number()})
    .default({x: 0.5, y: 0.5}),
  // Куда лёг блок текста и на сколько отступил от своего края. Решает
  // питон: он знает рамку лица и высоту блока, а обложка с заголовком
  // поперёк лица — брак, который замечает уже человек на готовом ролике.
  coverAnchor: z.enum(['top', 'bottom']).default('bottom'),
  coverInset: z.number().default(0),

  title: z.string().optional(),       // заголовок темы, на первом кадре
  coverLines: z.array(coverLine).default([]),
  coverFont: z.string().default('Manrope'),
  coverWeight: z.number().default(800),
  titleColor: z.string().default('#FFFFFF'),
  titleSize: z.number().default(38),
  scrim: z.number().default(0.28),
  hook: z.string().optional(),        // хук, там же и в кадре без звука
  cta: z.string().optional(),         // текст последней карточки
  brandName: z.string().optional(),

  brandColor: z.string().default('#111111'),   // фон карточек
  accentColor: z.string().default('#C97C5D'),  // активное слово караоке
  captionTextColor: z.string().default('#fff'),  // базовый цвет субтитра

  width: z.number().default(1080),
  height: z.number().default(1920),
  fps: z.number().default(30),
  introSeconds: z.number().default(1.4),
  outroSeconds: z.number().default(1.8),

  // Натуральный кадр дубля: без него не посчитать кроп под 9:16.
  videoWidth: z.number(),
  videoHeight: z.number(),

  // Что осталось от дубля после выброшенных пауз. Один кусок на всё
  // видео — значит не резали.
  segments: z.array(segment).min(1),

  // Куда едет кадр. Пусто — стоим по центру, как раньше.
  pan: z.array(focus).default([]),

  // Фото поверх кадра. Пусто — накладок нет, и это молчаливый дефолт:
  // материал альбома по умолчанию идёт на панель сплита, а не сюда.
  inserts: z.array(insert).default([]),

  // Слои поверх дубля. Пусто — формат обычный, и это тоже молчаливый
  // дефолт: слои заводит отдельная работа Монтажёра, а не каждый монтаж.
  layers: z.array(layer).default([]),
  // Рукописная гарнитура акцента и сжатая гарнитура заголовка. Имена
  // проверяет питон по тому же списку, по которому их грузит шаблон.
  scriptFont: z.string().default('Caveat'),
  layerFont: z.string().default('FiraSansCondensed'),

  // Караоке. Пусто — субтитров нет (нет звука или нет речи), и тогда
  // на первые секунды возвращается титул хука.
  pages: z.array(page).default([]),

  // Маскот на фоне. Нет поля — нет и маскота: он украшение, а не часть
  // ролика, и молчаливый дефолт посадил бы знак в кадр каждого монтажа.
  // Куда его ставить, считает питон по рамке лица; здесь только рисуем.
  mascot: z.object({
    x: z.number(),
    y: z.number(),
    size: z.number(),
    color: z.string().default('#D97757'),
    opacity: z.number().default(0.9),
    glow: z.number().default(0.22),
    face: z.boolean().default(true),
    // Имя файла внутри public/: у бренда своя картинка маскота, и тогда
    // нарисованная звезда не собирается вовсе.
    src: z.string().optional(),
    // Секунда готового ролика, на которой маскот уходит. Нет поля —
    // стоит до конца. Уходит он растворяясь: щелчок на месте пропажи
    // читается браком склейки, а не решением.
    until: z.number().optional(),
  }).optional(),

  // Силуэт человека покадрово: папка масок внутри public/ и частота, с
  // которой они сняты. Есть поле — кусок рисуется дважды, и между двумя
  // копиями ложится маскот. Нет — маскот остаётся поверх картинки, как
  // было до 18.09.
  personMask: z.object({
    dir: z.string(),
    fps: z.number().default(30),
  }).optional(),

  // Музыка под роликом. Нет поля — ролик идёт со своим звуком.
  music: musicProps.optional(),
});

export type ReelProps = z.infer<typeof reelPropsSchema>;
