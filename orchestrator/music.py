"""Музыкальная подложка ролика: банк треков бренда и выбор под тему.

Решается здесь ровно три вещи — какие треки у бренда есть, какой из них
берёт эта тема и насколько тихо он идёт под голосом. Рисует дорожку
Remotion (`Music.tsx`), выравнивает итоговую громкость `footage.normalize`
после рендера; этот модуль между ними только выбирает файл и уровни.

Банк — папка `design/music/` в репозитории бренда, рядом с `photos/`, и
наполняет её человек. Это и есть выключатель: **пустой банк значит «не
надо»**, а не «ещё не дошли руки». Молчаливый дефолт тут обошёлся бы
дорого — музыка меняет ролик целиком, и подложка, приехавшая сама,
выглядит не решением, а поломкой.
"""
from __future__ import annotations

import hashlib
import logging
import re
from pathlib import Path

log = logging.getLogger("music")

BANK = "design/music"

# Что считаем треком. Решает расширение, а не проба файла: банк человек
# наполняет руками, и mp4 с видео туда не кладут.
SUFFIX = (".mp3", ".m4a", ".aac", ".wav", ".flac", ".ogg", ".opus")

# Громкость подложки, долей от полной. Под речью музыка на семнадцать
# децибел ниже голоса (20·lg 0,14), в открытых кадрах — на семь с
# половиной. Числа не на глаз: ниже `BED` подложка перестаёт слышаться
# вовсе и платить за неё весом файла не за что, выше — начинает
# соперничать с голосом на согласных, и речь теряет разборчивость
# раньше, чем это становится заметно на глаз по волне.
BED = 0.14
OPEN = 0.42

# Слова, которыми человек снимает музыку с этого ролика. Банк при этом
# остаётся: отказ здесь одноразовый, а не настройка.
OFF_RX = re.compile(
    r"без\s+(музык|подложк|фоновой\s+музык|саундтрек|трека)"
    r"|музык\w*\s+не\s+надо"
    r"|(выключи|убери|сними)\s+музык",
    re.I)


def wanted(ask: str) -> bool:
    """Музыка под этот ролик нужна? Слова просьбы сильнее банка."""
    return not OFF_RX.search(ask or "")


def bank(b) -> list[Path]:
    """Треки бренда, в одном и том же порядке на любой машине.

    Сортировка по имени, а не по времени файла: порядок входит в выбор
    трека, а `mtime` переживает `git clone` не всегда — тот же ролик
    пересобрался бы с другой музыкой на второй машине.
    """
    root = b.path(BANK)
    if not root.is_dir():
        return []
    return sorted((p for p in root.iterdir()
                   if p.is_file() and p.suffix.lower() in SUFFIX),
                  key=lambda p: p.name)


def pick(b, theme_id: str) -> Path | None:
    """Трек этой темы. Один и тот же при каждой пересборке.

    Выбор по отпечатку id, а не случайный и не по счётчику: правка
    субтитров пересобирает ролик заново, и человек, поправивший одно
    слово, получил бы ролик с другой музыкой. Тем же правилом живут
    блоки панели — ролик обязан приехать тот же.

    `hash()` тут не годится: он солится на каждый запуск процесса.
    """
    tracks = bank(b)
    if not tracks:
        return None
    digest = hashlib.sha1(theme_id.encode("utf-8")).digest()
    return tracks[int.from_bytes(digest[:4], "big") % len(tracks)]


def spec(b, theme_id: str, ask: str = "") -> tuple[Path | None, str]:
    """Что положить под ролик и что сказать человеку.

    Отдаёт файл и строку. Строка пустая, когда говорить нечего:
    человек, снявший музыку словами, не нуждается в напоминании, что
    музыки нет, а молчание на пустом банке честнее уговоров наполнить
    его — банк пустой, потому что его не наполняли.
    """
    if not wanted(ask):
        return None, ""
    track = pick(b, theme_id)
    if track is None:
        return None, ""
    return track, f"музыка под роликом: {track.stem}"


def props(name: str) -> dict[str, float | str]:
    """Блок `music` для Remotion. Имя — файла внутри public/."""
    return {"src": name, "bed": BED, "open": OPEN}
