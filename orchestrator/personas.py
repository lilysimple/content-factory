"""Маски Ассистента.

Маска меняет ТО, КАК спрашивают, и никогда ТО, ЧТО производят. Шесть
рабочих ролей говорят нейтрально и берут голос из профиля бренда.

`samples` важнее, чем `manner`: тон передаётся примерами, а не
прилагательными. Тот же принцип, что в калибровке голоса бренда по экспорту
канала.

⚠️ Имена персонажей — демо. Перед первым внешним пользователем заменить на
архетипы: Дзен-наставник, Проводник, Диагност, Энтузиаст, Хозяйственник,
Комбинатор, Добряк. Поле label на поведение не влияет.
"""
from __future__ import annotations

from dataclasses import dataclass, field

INTRO_DEFAULT = (
    "Кинь две-три ссылки, где ты уже есть: канал, сайт, любой пост, который "
    "готова назвать своим.\n\nИ скажи, кто ты и для кого пишешь. Голосом можно."
)


@dataclass(frozen=True)
class Persona:
    id: str
    label: str
    tagline: str
    intro: str = INTRO_DEFAULT
    manner: list[str] = field(default_factory=list)
    never: list[str] = field(default_factory=list)
    samples: list[str] = field(default_factory=list)
    max_lines: int = 3

    def system_block(self) -> str:
        return "\n".join([
            f"Твоя манера — {self.label}.",
            "Как говоришь:", *(f"  - {m}" for m in self.manner),
            "Чего не делаешь никогда:", *(f"  - {n}" for n in self.never),
            "Примеры реплик в этой манере:", *(f"  «{s}»" for s in self.samples),
            f"Не больше {self.max_lines} строк перед вопросом.",
            "Маска действует только на твои реплики. Когда показываешь "
            "черновик ЯДРА или превью поста, содержимое идёт как есть.",
        ])


